#!/usr/bin/env python3
"""Reads tools/state_republic_map.csv and (idempotently):
 1. adds add_core_of = <TAG> to history/states/*.txt
 2. writes common/scripted_effects/YGwar_secession_effects.txt (YGwar_secede_<TAG>)
 3. fixes capital = N in history/countries/<TAG>*.txt
Primary republics (SVN CRO BOS SER VOJ KOS MNT MAC) must cover all 100 states exactly once.
RSK/RSB/HRZ are claims inside CRO/BOS states."""
import csv, glob, re, os, sys, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = {}
with open(os.path.join(ROOT,'tools','state_republic_map.csv'), encoding='utf-8') as f:
    for r in csv.DictReader(f, delimiter=';'):
        rows[r['tag']] = [int(x) for x in r['state_ids'].split(',')]
PRIMARY = ['SVN','CRO','BOS','SER','VOJ','KOS','MNT','MAC']
CLAIMS = ['RSK','RSB','HRZ']
CAPITAL = json.load(open(os.path.join(ROOT,'tools','_capitals.json')))  # written by rebuild_states.py
seen = {}
for t in PRIMARY:
    for s in rows[t]:
        assert s not in seen, f'state {s} in {seen[s]} and {t}'
        seen[s] = t
assert sorted(seen) == list(range(1,len(seen)+1)), 'primary mapping must cover 1..100: missing %s' % (set(range(1,len(seen)+1))-set(seen))
for t in CLAIMS:
    for s in rows[t]:
        assert s in seen, s
core_tags = {s:[seen[s]] for s in seen}
for t in CLAIMS:
    for s in rows[t]: core_tags[s].append(t)
# RSK states are CRO-primary: primary list above already holds them under CRO
for s in sorted(seen):
    fn = glob.glob(os.path.join(ROOT,'history','states','%03d_*.txt' % s))
    assert len(fn)==1, s
    txt = open(fn[0], encoding='utf-8').read()
    for t in core_tags[s]:
        line = f'add_core_of = {t}'
        if line not in txt:
            txt = re.sub(r'([ \t]*)add_core_of = YUG\n', lambda m: m.group(0)+m.group(1)+line+'\n', txt, count=1)
    open(fn[0],'w',encoding='utf-8').write(txt)
# secession effects
out = ['# GENERATED by tools/build_territories.py - edit tools/state_republic_map.csv, not this file.',
       '# Scope: any country (usually YUG). transfer_state is called inside the receiving country scope.','']
def effect(tag, states, who):
    o = [f'YGwar_secede_{tag}_{who} = {{']
    o.append(f'\t{tag} = {{')
    for s in states:
        o.append(f'\t\ttransfer_state = {s}')
        o.append(f'\t\t{s} = {{ add_core_of = {tag} }}')  # re-assert the national core after the transfer
    o.append(f'\t\tset_capital = {CAPITAL[tag]}')
    o.append(f'\t\tset_country_flag = YGwar_{tag}_emerged')
    o.append('\t}')
    o.append('}')
    return o
for t in PRIMARY:
    own = [s for s in rows[t] if not (t=='CRO' and s in rows['RSK'])]
    states = rows[t]
    out += effect(t, states, 'all')
    if t=='CRO':
        out += effect(t, own, 'core')   # without RSK-claimed states
    if t=='BOS':
        own = [s for s in rows['BOS'] if s not in rows['RSB'] and s not in rows['HRZ']]
        out += effect(t, own, 'core')
for t in CLAIMS:
    out += effect(t, rows[t], 'all')
open(os.path.join(ROOT,'common','scripted_effects','YGwar_secession_effects.txt'),'w',encoding='utf-8').write('\n'.join(out)+'\n')
# capitals
for t,c in CAPITAL.items():
    fn = glob.glob(os.path.join(ROOT,'history','countries',t+' - *.txt'))[0]
    txt = open(fn,encoding='utf-8').read()
    txt = re.sub(r'^capital = \d+', f'capital = {c}', txt, count=1, flags=re.M)
    open(fn,'w',encoding='utf-8').write(txt)
print('ok', len(seen), 'states mapped')
